import { readFile, writeFile } from 'node:fs/promises';
import { palettes } from './palettes.mjs';
import { semanticTokenColors, tokenColors } from './syntax.mjs';
import { workbenchColors } from './workbench.mjs';

const packageRoot = new URL('../', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('package.json', packageRoot), 'utf8'));
const uiThemes = { dark: 'vs-dark', light: 'vs', 'high-contrast': 'hc-black' };
const colorRoles = [
  'foreground',
  'muted',
  'accent',
  'keywords',
  'strings',
  'numbers',
  'variables',
  'functions',
  'methods',
  'types',
  'members',
  'tags',
  'styles',
  'regex',
  'error',
  'warning',
  'success',
  'info',
];
const checkOnly = process.argv.includes('--check');

function luminance(hex) {
  const channel = (offset) => {
    const value = Number.parseInt(hex.slice(offset, offset + 2), 16) / 255;
    return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * channel(1) + 0.7152 * channel(3) + 0.0722 * channel(5);
}

function assertContrast(id, role, foreground, background, threshold) {
  const values = [luminance(foreground), luminance(background)].sort((a, b) => b - a);
  const ratio = (values[0] + 0.05) / (values[1] + 0.05);
  if (ratio < threshold) {
    throw new Error(
      `${id} ${role} has ${ratio.toFixed(2)}:1 contrast. Expected at least ${threshold}:1.`,
    );
  }
}

async function output(relativePath, contents) {
  const file = new URL(relativePath, packageRoot);
  if (!checkOnly) {
    await writeFile(file, contents);
    return;
  }
  if ((await readFile(file, 'utf8')) !== contents) {
    throw new Error(`${relativePath} differs from generated output. Run npm run build.`);
  }
}

const themeMetadata = [];
if (manifest.contributes.themes.length !== palettes.length)
  throw new Error('Invalid theme contribution count.');
for (const palette of palettes) {
  const label = `SyntaxCraft ${palette.name}`;
  const definition = manifest.contributes.themes.find((theme) => theme.id === label);
  const path = `themes/${palette.id}-color-theme.json`;
  if (
    definition?.label !== label ||
    definition.uiTheme !== uiThemes[palette.variant] ||
    definition.path !== `./${path}`
  ) {
    throw new Error(`Missing or inconsistent theme contribution for ${label}.`);
  }
  const minimumContrast = palette.variant === 'high-contrast' ? 7 : 4.5;
  for (const role of colorRoles) {
    assertContrast(palette.id, role, palette[role], palette.background, minimumContrast);
  }
  assertContrast(
    palette.id,
    'foreground on selection',
    palette.foreground,
    palette.selection,
    minimumContrast,
  );
  assertContrast(
    palette.id,
    'foreground on accent',
    palette.onAccent,
    palette.accent,
    minimumContrast,
  );
  assertContrast(palette.id, 'foreground on warning', palette.onAccent, palette.warning, 4.5);

  await output(
    path,
    JSON.stringify(
      {
        $schema: 'vscode://schemas/color-theme',
        name: label,
        type: palette.variant === 'light' ? 'light' : 'dark',
        semanticHighlighting: true,
        colors: workbenchColors(palette),
        tokenColors: tokenColors(palette),
        semanticTokenColors: semanticTokenColors(palette),
      },
      null,
      2,
    ) + '\n',
  );

  themeMetadata.push({
    id: palette.id,
    label,
    background: palette.background,
    foreground: palette.foreground,
    variant: palette.variant,
    accent: palette.accent,
    palette: {
      Variables: palette.variables,
      Functions: palette.functions,
      Types: palette.types,
      Members: palette.members,
      Syntax: palette.keywords,
      Markup: palette.tags,
      Styles: palette.styles,
      Literals: palette.strings,
    },
    comment: palette.muted,
    string: palette.strings,
    number: palette.numbers,
    functionColor: palette.functions,
    typeColor: palette.types,
  });
}

await output(
  'src/theme-catalog.ts',
  '// Generated by scripts/generate.mjs. Edit scripts/palettes.mjs to change these values.\n' +
    '// prettier-ignore\n' +
    `export const themes = ${JSON.stringify(themeMetadata, null, 2)} as const;\n`,
);
